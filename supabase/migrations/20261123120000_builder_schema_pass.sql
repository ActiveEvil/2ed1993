CREATE OR REPLACE FUNCTION "public"."refuse_misparented_choice"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
BEGIN
    IF NEW."parent_id" IS NOT NULL AND EXISTS (
        SELECT 1 FROM "public"."saved_list_choices" AS "p"
        WHERE "p"."id" = NEW."parent_id" AND "p"."kind" <> 'vehicle_card'
    ) THEN
        RAISE EXCEPTION 'saved_list_choices %: parent % is not a vehicle_card choice', NEW."id", NEW."parent_id"
            USING ERRCODE = 'check_violation';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD."kind" = 'vehicle_card' AND NEW."kind" <> 'vehicle_card' AND EXISTS (
        SELECT 1 FROM "public"."saved_list_choices" AS "c"
        WHERE "c"."parent_id" = OLD."id"
    ) THEN
        RAISE EXCEPTION 'saved_list_choices %: a vehicle_card choice with rows cannot change kind', OLD."id"
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

