-- The guard

CREATE OR REPLACE FUNCTION "public"."refuse_unredirected_change"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
DECLARE
    "i" integer := 0;
    "used" boolean := false;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW."id" = OLD."id" THEN
        RETURN NEW;
    END IF;
    WHILE "i" < TG_NARGS AND NOT "used" LOOP
        EXECUTE format('SELECT EXISTS (SELECT 1 FROM "public".%I WHERE %I = $1)', TG_ARGV["i"], TG_ARGV["i" + 1])
            INTO "used" USING OLD."id";
        "i" := "i" + 2;
    END LOOP;
    IF "used" AND TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION '% id % is used by a saved list; its id cannot change', TG_TABLE_NAME, OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF "used" AND NOT EXISTS (
        SELECT 1 FROM "public"."catalogue_redirects" AS "r"
        WHERE "r"."table_name" = TG_TABLE_NAME::"text" AND "r"."old_id" = OLD."id"
    ) THEN
        RAISE EXCEPTION '% id % is used by a saved list and has no redirect', TG_TABLE_NAME, OLD."id"
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

ALTER FUNCTION "public"."refuse_unredirected_change"() OWNER TO "postgres";

COMMENT ON FUNCTION "public"."refuse_unredirected_change"() IS 'Guards a catalogue row that saved lists name. Refuses its deletion unless catalogue_redirects holds a row for it, and refuses any change of its id. The trigger''s arguments are pairs of saved list table and column that name the guarded table.';

